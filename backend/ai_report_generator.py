@report_bp.route('/generate', methods=['POST'])
def generate_report():
    """
    Generate security report
    
    Request body:
    {
        "findings": "List of findings",
        "target": "Target name",
        "assessment_type": "Penetration Test",
        "assessor": "Your Name",
        "tools_used": ["nmap", "burp"],
        "include_pdf": false
    }
    """
    try:
        data = request.get_json()
        
        findings = data.get('findings', '')
        target = data.get('target', '')
        
        if not findings or not target:
            return jsonify({
                'success': False,
                'error': 'Missing required fields: findings, target'
            }), 400
        
        assessment_type = data.get('assessment_type', 'Penetration Test')
        assessor = data.get('assessor', 'ShadowHack Team')
        tools_used = data.get('tools_used', [])
        include_pdf = data.get('include_pdf', False)
        
        # Run async function
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        try:
            generator = get_report_generator()
            result = loop.run_until_complete(
                generator.generate_report(
                    findings=findings,
                    target=target,
                    assessment_type=assessment_type,
                    assessor=assessor,
                    tools_used=tools_used,
                    include_pdf=include_pdf
                )
            )
            return jsonify(result)
        finally:
            loop.close()
    
    except Exception as e:
        logger.error(f"Report generation error: {str(e)}")
        return jsonify({
            'success': False,
            'error': str(e)
        }), 500

@report_bp.route('/template', methods=['GET'])
def get_template():
    """Get report template"""
    try:
        return jsonify({
            'success': True,
            'template': ReportGenerator.REPORT_TEMPLATE
        })
    except Exception as e:
        return jsonify({
            'success': False,
            'error': str(e)
        }), 500

@report_bp.route('/export/<format>', methods=['POST'])
def export_report(format):
    """
    Export report in different formats
    
    Supported formats: markdown, html, pdf, json
    """
    try:
        data = request.get_json()
        report_content = data.get('report_content', '')
        filename = data.get('filename', f'report_{datetime.now().strftime("%Y%m%d_%H%M%S")}')
        
        if format == 'markdown':
            return {
                'content': report_content,
                'mime_type': 'text/markdown',
                'filename': f"{filename}.md"
            }
        
        elif format == 'html':
            html = markdown.markdown(report_content)
            return {
                'content': html,
                'mime_type': 'text/html',
                'filename': f"{filename}.html"
            }
        
        elif format == 'json':
            return {
                'content': json.dumps({'report': report_content}, indent=2),
                'mime_type': 'application/json',
                'filename': f"{filename}.json"
            }
        
        else:
            return jsonify({
                'success': False,
                'error': f'Unsupported format: {format}'
            }), 400
    
    except Exception as e:
        logger.error(f"Export error: {str(e)}")
        return jsonify({
            'success': False,
            'error': str(e)
        }), 500
